-- 取込済み明細のマイナス金額を正規化する。
-- JCBのキャッシュバック（ＭｙＪＣＢ　Ｐａｙポイント利用など）や返金・取消行は
-- CSVのご利用金額列がマイナス表記で、これまで「金額がマイナスの支出」として
-- 保存されていた。請求からの控除＝実質的な収入なので、符号を反転して収入に振り替える。
-- 以後の取込は shared/csv.ts の parseCsv が同じ正規化を行う。
--
-- 注意: import_hash は取込時にJS側でSHA-256計算するためSQLでは再計算できず、
-- ここで振り替えた行のハッシュは反転前の値のまま残る。過去と同じCSVを再取込すると
-- 該当行だけ重複判定が効かず二重登録されうる（取込プレビューの重複件数で確認可能）。
UPDATE transactions
SET
  amount = -amount,
  type = CASE type WHEN '支出' THEN '収入' ELSE '支出' END
WHERE amount < 0;
